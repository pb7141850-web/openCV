import cv2
import numpy as np
from google.colab.patches import cv2_imshow

# read an image
img=cv2.imread("/content/fruit.png")
print(type(img))

print(img.shape)

# resizing the image
img_resize=cv2.resize(img,(128,128))
cv2_imshow(img_resize)
print(img_resize.shape)

cv2_imshow(img_resize)

#convert rgb to grayscale
img_gray = cv2.cvtColor(img_resize, cv2.COLOR_BGR2GRAY)
cv2_imshow(img_gray)

print(img_gray.shape)

img_resize[:,:,0]=0
cv2_imshow(img_resize)

img_resize[:,:,2]=0
cv2_imshow(img_resize)

imgBlue=img[:,:,0]
imgGreen=img[:,:,1]
imgRed=img[:,:,2]
new_img=np.hstack((imgBlue, imgGreen, imgRed))
cv2_imshow(new_img)

# flipping the image
img_flip=cv2.flip(img_resize,0)  # upside down
# -1 for left to right and upside down
#  1 for left to right
cv2_imshow(img_flip)

# cropping the image
img_crop=img_resize[100:300,100:300]
cv2_imshow(img_crop)

# save the image
cv2.imwrite("new_img.png",img_crop)

img1=np.zeros((512,512,3), dtype=np.uint8)
# cv2_imshow( img1)
# rectangle
cv2.rectangle(img1,(100,100),pt2=(300,300),color=(255,0,0),thickness=3)
#circle
cv2.circle(img1,center=(100,400),radius=50,color=(0,255,0),thickness=3)
#line
cv2.line(img1,pt1=(0,0),pt2=(512,512),thickness=2,color=(0,0,255))
#text
cv2.putText(img1,org=(100,100),fontScale=4,color=(0,255,255),thickness=2,lineType=cv2.LINE_AA,text="hello",fontFace=cv2.FONT_HERSHEY_SIMPLEX)
small_img = cv2.resize(img1, (128,128))
cv2_imshow(small_img)

